var PAISES_IDX = (function(){
  var m = {};
  function k(t){ return String(t == null ? "" : t).normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/\s+/g, " ").trim(); }
  PAISES.forEach(function(p){ [p.pais, p.nome, p.a2, p.a3].forEach(function(t){ var c = k(t); if(c && !m[c]) m[c] = p; }); });
  m._k = k;
  return m;
})();

/* Acha o país a partir do que foi digitado (nome do país, nome da bandeira ou código). Devolve null se não achar. */
function acharPais(txt){ var c = PAISES_IDX._k(txt); return c ? (PAISES_IDX[c] || null) : null; }
/* Bandeirinha pronta para colocar no HTML ("" se o texto não for um país da lista). */
function bandeiraHtml(txt){
  var p = acharPais(txt); if(!p) return "";
  return '<img class="flag" src="' + p.svg + '" alt="Bandeira: ' + p.pais + '" title="' + p.pais + '" width="20" height="15" loading="lazy" decoding="async" onerror="this.remove()">';
}

